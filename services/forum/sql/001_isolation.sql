-- CFP+ Forum • 001 • Cô lập 3 khối dữ liệu trong MỘT database Postgres (Supabase sandbox)
-- Tương đương 3 database: mỗi khối một schema + một role riêng, không role nào đọc được schema khác.
-- Supabase API roles (anon, authenticated) không có quyền gì; RLS bật + FORCE trên mọi bảng.
-- Idempotent: chạy lại an toàn.
begin;
-- ===== forum_auth (chỉ role forum_auth_app truy cập)
do $$ begin
  if not exists (select 1 from pg_roles where rolname = 'forum_auth_app') then
    create role forum_auth_app nologin noinherit;  -- mật khẩu/LOGIN do người vận hành cấp, không nằm trong repo
  end if;
end $$;
create schema if not exists forum_auth;
revoke all on schema forum_auth from public;
create table if not exists forum_auth.users (
  id integer generated by default as identity primary key, email varchar(254) not null unique,
  name varchar(60) not null, pw_hash varchar(255) not null, created_at timestamptz not null default now());
create table if not exists forum_auth.sessions (
  token_hash varchar(64) primary key, user_id integer not null references forum_auth.users(id),
  expires_at timestamptz not null);
revoke all on forum_auth.users from public;
alter table forum_auth.users enable row level security;
alter table forum_auth.users force row level security;
drop policy if exists forum_auth_app_all on forum_auth.users;
create policy forum_auth_app_all on forum_auth.users for all to forum_auth_app using (true) with check (true);
revoke all on forum_auth.sessions from public;
alter table forum_auth.sessions enable row level security;
alter table forum_auth.sessions force row level security;
drop policy if exists forum_auth_app_all on forum_auth.sessions;
create policy forum_auth_app_all on forum_auth.sessions for all to forum_auth_app using (true) with check (true);
grant usage on schema forum_auth to forum_auth_app;
grant select, insert, update, delete on all tables in schema forum_auth to forum_auth_app;
grant usage, select on all sequences in schema forum_auth to forum_auth_app;
alter role forum_auth_app set search_path = forum_auth;

